@router.get("/api/export-pdf")
@router.get("/api/projects/{project_id}/export-pdf")
async def get_pdf_report(
    session_id: Optional[str] = None,
    project_id: Optional[str] = None,
    report_title: Optional[str] = None,
    analysis_id: Optional[str] = None,
):
    """Generates and streams back the executive PDF report, or a distinct capability report if analysis_id is provided."""
    target_id = project_id or session_id
    if not target_id or target_id == "default":
        target_id = "new_project_tb_burden"

    session_dir = get_safe_session_dir(target_id)
    results_path = session_dir / "results.json"
    cleaned_csv = session_dir / "cleaned.csv"

    if not results_path.exists():
        raise HTTPException(status_code=400, detail="Data analysis results not available.")

    with open(results_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    meta = get_project_metadata(target_id)
    title = report_title.strip() if report_title else meta.get("report_title", meta.get("name", "Analysis Report"))
    goal = meta.get("optimized_goal") or meta.get("goal") or ""

    if cleaned_csv.exists():
        df = read_csv_robust(cleaned_csv)
    elif (session_dir / "original_upload.csv").exists():
        df = read_csv_robust(session_dir / "original_upload.csv")
    else:
        df = pd.DataFrame()

    report_dict = {
        "dataframe":           df,
        "cleaning_steps":      data.get("cleaning_steps", ""),
        "relations":           data.get("relations", ""),
        "insights":            data.get("insights", ""),
        "code":                data.get("code", ""),
        "output_dir":          str(get_safe_output_dir(target_id)),
        "report_title":        title,
        "goal":                goal,
        "categories":          data.get("categories", {}),
        "executive_narrative": data.get("executive_narrative", ""),
        "executive_findings":  data.get("executive_findings", []),
        "predictive":          data.get("predictive", ""),
        "anomaly":             data.get("anomaly", ""),
        "trend":               data.get("trend", ""),
    }

    try:
        modules = load_crew_modules()
        _export_pdf = modules["export_pdf"]
        if not _export_pdf:
            raise RuntimeError("PDF export module unavailable.")
        pdf_bytes = _export_pdf(report_dict, analysis_id=analysis_id)
        if analysis_id:
            clean_aid = re.sub(r"[^a-zA-Z0-9_-]", "_", str(analysis_id).lower())
            filename = f"{clean_aid}_{target_id}"
        else:
            filename = re.sub(r"[^a-zA-Z0-9_-]", "_", title.lower())[:60] or f"report_{target_id}"
        return StreamingResponse(
            BytesIO_iterator(pdf_bytes),
            media_type="application/pdf",
            headers={"Content-Disposition": f"attachment; filename={filename}.pdf"}
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"PDF generation failed: {e}")

@router.get("/api/projects/{project_id}/artifacts/{artifact_key}")
@router.get("/api/artifacts/{artifact_key}")
async def get_artifact(
    artifact_key: str,
    project_id: Optional[str] = None,
    session_id: Optional[str] = None
):
    """Securely streams back an analytical CSV or JSON artifact generated by an agent."""
    target_id = project_id or session_id
    if not target_id or not is_safe_filename(artifact_key):
        raise HTTPException(status_code=400, detail="Invalid artifact request.")

    from tools.artifact_manager import ArtifactManager
    target_file = ArtifactManager.get_artifact_file(target_id, artifact_key)
    if not target_file or not target_file.exists():
        raise HTTPException(status_code=404, detail="Artifact file not found.")

    media_type = "text/csv" if artifact_key.endswith(".csv") else "application/json"
    return FileResponse(
        str(target_file),
        media_type=media_type,
        filename=artifact_key,
        headers={"Content-Disposition": f"attachment; filename={artifact_key}"}
    )

