@router.post("/api/export/webhook")
async def export_webhook(
    session_id: str = Form(...),
    webhook_url: str = Form(...)
):
    """(Enterprise) Export PDF report directly to a Slack/Discord webhook."""
    import requests
    url = (webhook_url or "").strip()
